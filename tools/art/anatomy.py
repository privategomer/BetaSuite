"""Body point lists for the figure art.

Each body is a dict of named point lists in the 600 x 1200 canvas. Left
halves (viewer's left, x < 300) are listed; the right half is mirrored. The
front view raises the figure's right arm (viewer's left) behind the head so
the armpit is visible; the back view raises the same arm, which is then on
the viewer's right.

Two body builds exist: "shared" (styles flat, ink and cel) and "angular"
(its own heavier proportions). Male bodies are shared by every style.
Anatomy is shape and shading only: no genital detail.
"""
