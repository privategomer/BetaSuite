_PIT = [(216, 266), (226, 288), (236, 308), (244, 296), (244, 278), (232, 264)]
_PIT_CREASE = [(228, 272), (238, 292), (242, 314)]
# a short sleeve covers the upper arm up to this far along the arm's axis
_AXIS = (-0.238, -0.971)
_SLEEVE_LEN = 95
_ANCHOR = (234, 300)


def _raised(dx, k):
    ax, ay = _ANCHOR

    def t(p):
        return shift(scale(p, ax, ay, k), dx, 0)
    a, b = _AXIS
    # keep a*x + b*y <= c: the part of the arm nearer the shoulder
    cut = (a, b, _SLEEVE_LEN * k + a * (ax + dx) + b * ay)
    return dict(upper=t(_UPPER), fore=t(_FORE), pit=t(_PIT),
                pit_crease=t(_PIT_CREASE), sleeve_cut=cut)


