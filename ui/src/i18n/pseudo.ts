// The pseudo-locale: every formatted string accented, padded by 40 percent
// and bracketed. Text on screen without accents never went through the
// catalog; a layout that clips or wraps badly cannot take translations,
// which run 30 to 40 percent longer than English.
const ACCENTED: Readonly<Record<string, string>> = {
  a: 'á', b: 'ƀ', c: 'ç', d: 'ð', e: 'é', f: 'ƒ', g: 'ĝ', h: 'ĥ', i: 'í', j: 'ĵ', k: 'ķ', l: 'ļ', m: 'ɱ',
  n: 'ñ', o: 'ó', p: 'þ', q: 'ǫ', r: 'ŕ', s: 'š', t: 'ţ', u: 'ú', v: 'ṽ', w: 'ŵ', x: 'ẋ', y: 'ý', z: 'ž',
  A: 'Å', B: 'Ɓ', C: 'Ç', D: 'Ð', E: 'É', F: 'Ƒ', G: 'Ĝ', H: 'Ĥ', I: 'Î', J: 'Ĵ', K: 'Ķ', L: 'Ļ', M: 'Ṁ',
  N: 'Ñ', O: 'Ö', P: 'Þ', Q: 'Ǫ', R: 'Ŕ', S: 'Š', T: 'Ţ', U: 'Û', V: 'Ṽ', W: 'Ŵ', X: 'Ẋ', Y: 'Ý', Z: 'Ž',
};

const PADDING = 0.4;

export function pseudo( text: string ): string {
  const accented = text.replace( /[A-Za-z]/g, ( letter ) => ACCENTED[ letter ] ?? letter );
  const padding = '~'.repeat( Math.ceil( text.length * PADDING ) );
  return `[${accented}${padding}]`;
}
